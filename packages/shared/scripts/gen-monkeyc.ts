/**
 * Generates Monkey C constants for the watch from the shared region table.
 * Output (committed; re-run `pnpm codegen` after editing regions.ts or regenerating raions.ts):
 * - apps/watch/source/generated/Regions.mc: region IDs and names, in every scope (glance, background).
 * - apps/watch/resources/generated/raions.json + raions.xml: raions per oblast for the picker. A
 *   resource, loaded only in the foreground, so the glance and background never pay for it.
 * - apps/watch/resources/generated/settings.xml: properties and the phone settings (regions and raions).
 */
import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Flag, Level, Source } from '../src/levels.ts';
import { RAIONS } from '../src/raions.ts';
import { DEFAULT_REGION_ID, REGION_BY_ID, REGIONS } from '../src/regions.ts';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../../..');
const outFile = resolve(root, 'apps/watch/source/generated/Regions.mc');

const mcString = (s: string) => `"${s.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
const list = (items: readonly string[], indent = '        ') =>
  `[\n${items.map((i) => `${indent}${i}`).join(',\n')}\n    ]`;

// Picker order: alphabetical by Latin name, as indices into IDS/NAMES.
const pickerOrder = [...REGIONS].sort((a, b) => a.nameLatin.localeCompare(b.nameLatin, 'en')).map((r) => String(r.idx));

const source = `// GENERATED by packages/shared/scripts/gen-monkeyc.ts. Do not edit; run \`pnpm codegen\`.
import Toybox.Lang;

(:background, :glance)
module Regions {
    // Number of regions; also the length of the /v1/all status string.
    const COUNT = ${REGIONS.length};
    const DEFAULT_ID = ${DEFAULT_REGION_ID};

    // Canonical region IDs (ukrainealarm / siren.pp.ua regionId), in map order (idx).
    const IDS = ${list(REGIONS.map((r) => String(r.id)))} as Array<Number>;

    // Latin display names, same order as IDS.
    const NAMES = ${list(REGIONS.map((r) => mcString(r.nameLatin)))} as Array<String>;

    // Indices into IDS/NAMES, sorted alphabetically for the region picker.
    const PICKER_ORDER = [${pickerOrder.join(', ')}] as Array<Number>;

    // Returns the idx for a region ID, or -1 if unknown.
    function indexOf(id as Number) as Number {
        for (var i = 0; i < COUNT; i++) {
            if (IDS[i] == id) {
                return i;
            }
        }
        return -1;
    }

    function nameOf(id as Number) as String {
        var i = indexOf(id);
        return i >= 0 ? NAMES[i] : "?";
    }
}

(:background, :glance)
module Levels {
    const GREEN = ${Level.Green};
    const YELLOW = ${Level.Yellow};
    const RED = ${Level.Red};

    const FLAG_OWN_YELLOW = ${Flag.OwnYellow};
    const FLAG_PARTIAL = ${Flag.Partial};
    const FLAG_ARTILLERY = ${Flag.Artillery};
    const FLAG_URBAN_FIGHTS = ${Flag.UrbanFights};

    // Source the proxy is serving (\`s\`).
    const SOURCE_SIREN = ${Source.Siren};
    const SOURCE_TRYVOHA = ${Source.Tryvoha};
}
`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, source, 'utf8');
console.log(`wrote ${outFile} (${REGIONS.length} regions)`);

// Properties and phone-app settings (Garmin Connect) live in one generated resource file,
// so the region list always matches Regions.mc.
const xmlEscape = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
// One list on the phone: regions and "Oblast: Raion" entries, sorted by label so each oblast's
// raions follow it. The watch stores either kind of ID in regionId.
const byName = [
  ...REGIONS.map((r) => ({ id: r.id, label: r.nameLatin })),
  ...RAIONS.map((r) => ({ id: r.id, label: `${REGION_BY_ID.get(r.oblastId)?.nameLatin}: ${r.nameLatin}` })),
].sort((a, b) => a.label.localeCompare(b.label, 'en'));
const settingsFile = resolve(root, 'apps/watch/resources/generated/settings.xml');
const settingsXml = `<!-- GENERATED by packages/shared/scripts/gen-monkeyc.ts. Do not edit; run \`pnpm codegen\`. -->
<resources>
    <strings>
        <string id="SettingRegionTitle">Region</string>
        <string id="SettingProxyTitle">Proxy URL (empty = built-in)</string>
        <string id="SettingAlRedTitle">Prompt on air alert (red)</string>
        <string id="SettingAlYellowTitle">Prompt on partial / threat (yellow)</string>
        <string id="SettingAlGreenTitle">Prompt on all clear</string>
${byName.map((r) => `        <string id="Region${r.id}">${xmlEscape(r.label)}</string>`).join('\n')}
    </strings>

    <properties>
        <property id="regionId" type="number">${DEFAULT_REGION_ID}</property>
        <property id="proxyUrl" type="string"></property>
        <!-- Wake prompt per new level (plan D6); watch menu Alerts and the phone settings. -->
        <property id="alRed" type="boolean">true</property>
        <property id="alYellow" type="boolean">true</property>
        <property id="alGreen" type="boolean">true</property>
    </properties>

    <settings>
        <setting propertyKey="@Properties.regionId" title="@Strings.SettingRegionTitle">
            <settingConfig type="list">
${byName.map((r) => `                <listEntry value="${r.id}">@Strings.Region${r.id}</listEntry>`).join('\n')}
            </settingConfig>
        </setting>
        <setting propertyKey="@Properties.alRed" title="@Strings.SettingAlRedTitle">
            <settingConfig type="boolean" />
        </setting>
        <setting propertyKey="@Properties.alYellow" title="@Strings.SettingAlYellowTitle">
            <settingConfig type="boolean" />
        </setting>
        <setting propertyKey="@Properties.alGreen" title="@Strings.SettingAlGreenTitle">
            <settingConfig type="boolean" />
        </setting>
        <setting propertyKey="@Properties.proxyUrl" title="@Strings.SettingProxyTitle">
            <settingConfig type="alphaNumeric" />
        </setting>
    </settings>
</resources>
`;
mkdirSync(dirname(settingsFile), { recursive: true });
writeFileSync(settingsFile, settingsXml, 'utf8');
console.log(`wrote ${settingsFile}`);

// Raion picker data: one jsonData resource per oblast ([[raionId, "Latin name"], ...], alphabetical),
// so the picker parses only the raions it shows (one file for all ran out of memory on the menu page),
// plus RaionData.mc mapping oblast IDs to those resources (foreground only).
const raionsByOblast = new Map<number, [number, string][]>();
for (const r of [...RAIONS].sort((a, b) => a.nameLatin.localeCompare(b.nameLatin, 'en'))) {
  raionsByOblast.set(r.oblastId, [...(raionsByOblast.get(r.oblastId) ?? []), [r.id, r.nameLatin]]);
}
const oblastIds = [...raionsByOblast.keys()].sort((a, b) => a - b);
const genDir = resolve(root, 'apps/watch/resources/generated');
const raionDir = resolve(genDir, 'raions');
rmSync(resolve(genDir, 'raions.json'), { force: true });
rmSync(raionDir, { recursive: true, force: true });
mkdirSync(raionDir, { recursive: true });
for (const id of oblastIds) {
  writeFileSync(resolve(raionDir, `${id}.json`), `${JSON.stringify(raionsByOblast.get(id))}\n`, 'utf8');
}
writeFileSync(
  resolve(genDir, 'raions.xml'),
  `<!-- GENERATED by packages/shared/scripts/gen-monkeyc.ts. Do not edit; run the codegen script. -->
<resources>
${oblastIds.map((id) => `    <jsonData id="Raions${id}" filename="raions/${id}.json"/>`).join('\n')}
</resources>
`,
  'utf8',
);
writeFileSync(
  resolve(root, 'apps/watch/source/generated/RaionData.mc'),
  `// GENERATED by packages/shared/scripts/gen-monkeyc.ts. Do not edit; run \`pnpm codegen\`.
import Toybox.Lang;
import Toybox.WatchUi;

// Raion resources per oblast (foreground only; see Raions.mc).
module RaionData {
    // Oblasts that have raions.
    const OBLASTS = [${oblastIds.join(', ')}] as Array<Number>;

    // The oblast's raion list resource, or null if it has none.
    function resource(oblastId as Number) as ResourceId? {
${oblastIds.map((id) => `        if (oblastId == ${id}) {\n            return Rez.JsonData.Raions${id};\n        }`).join('\n')}
        return null;
    }
}
`,
  'utf8',
);
console.log(`wrote raions/*.json for ${oblastIds.length} oblasts (${RAIONS.length} raions) and RaionData.mc`);
