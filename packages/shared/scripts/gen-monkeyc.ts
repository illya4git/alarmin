/**
 * Generates Monkey C constants for the watch from the shared region table.
 * Output: apps/watch/source/generated/Regions.mc (committed; re-run `pnpm codegen` after editing regions.ts).
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Flag, Level } from '../src/levels.ts';
import { DEFAULT_REGION_ID, REGIONS } from '../src/regions.ts';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../../..');
const outFile = resolve(root, 'apps/watch/source/generated/Regions.mc');

const mcString = (s: string) => `"${s.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
const list = (items: readonly string[], indent = '        ') =>
  `[\n${items.map((i) => `${indent}${i}`).join(',\n')}\n    ]`;

// Picker order: alphabetical by Latin name, as indices into IDS/NAMES.
const pickerOrder = [...REGIONS].sort((a, b) => a.nameLatin.localeCompare(b.nameLatin, 'en')).map((r) => String(r.idx));

const source = `// GENERATED by packages/shared/scripts/gen-monkeyc.ts. Do not edit; run \`pnpm codegen\`.
import Toybox.Lang;

(:background, :glance)
module Regions {
    // Number of regions; also the length of the /v1/all status string.
    const COUNT = ${REGIONS.length};
    const DEFAULT_ID = ${DEFAULT_REGION_ID};

    // Canonical region IDs (ukrainealarm / siren.pp.ua regionId), in map order (idx).
    const IDS = ${list(REGIONS.map((r) => String(r.id)))} as Array<Number>;

    // Latin display names, same order as IDS.
    const NAMES = ${list(REGIONS.map((r) => mcString(r.nameLatin)))} as Array<String>;

    // Indices into IDS/NAMES, sorted alphabetically for the region picker.
    const PICKER_ORDER = [${pickerOrder.join(', ')}] as Array<Number>;

    // Returns the idx for a region ID, or -1 if unknown.
    function indexOf(id as Number) as Number {
        for (var i = 0; i < COUNT; i++) {
            if (IDS[i] == id) {
                return i;
            }
        }
        return -1;
    }

    function nameOf(id as Number) as String {
        var i = indexOf(id);
        return i >= 0 ? NAMES[i] : "?";
    }
}

(:background, :glance)
module Levels {
    const GREEN = ${Level.Green};
    const YELLOW = ${Level.Yellow};
    const RED = ${Level.Red};

    const FLAG_OWN_YELLOW = ${Flag.OwnYellow};
    const FLAG_PARTIAL = ${Flag.Partial};
    const FLAG_ARTILLERY = ${Flag.Artillery};
    const FLAG_URBAN_FIGHTS = ${Flag.UrbanFights};
}
`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, source, 'utf8');
console.log(`wrote ${outFile} (${REGIONS.length} regions)`);

// Properties and phone-app settings (Garmin Connect) live in one generated resource file,
// so the region list always matches Regions.mc.
const xmlEscape = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const byName = [...REGIONS].sort((a, b) => a.nameLatin.localeCompare(b.nameLatin, 'en'));
const settingsFile = resolve(root, 'apps/watch/resources/generated/settings.xml');
const settingsXml = `<!-- GENERATED by packages/shared/scripts/gen-monkeyc.ts. Do not edit; run \`pnpm codegen\`. -->
<resources>
    <strings>
        <string id="SettingRegionTitle">Region</string>
        <string id="SettingProxyTitle">Proxy URL (empty = built-in)</string>
${byName.map((r) => `        <string id="Region${r.id}">${xmlEscape(r.nameLatin)}</string>`).join('\n')}
    </strings>

    <properties>
        <property id="regionId" type="number">${DEFAULT_REGION_ID}</property>
        <property id="proxyUrl" type="string"></property>
        <!-- Wake prompt per new level (plan D6). No settings UI yet; all on. -->
        <property id="alRed" type="boolean">true</property>
        <property id="alYellow" type="boolean">true</property>
        <property id="alGreen" type="boolean">true</property>
    </properties>

    <settings>
        <setting propertyKey="@Properties.regionId" title="@Strings.SettingRegionTitle">
            <settingConfig type="list">
${byName.map((r) => `                <listEntry value="${r.id}">@Strings.Region${r.id}</listEntry>`).join('\n')}
            </settingConfig>
        </setting>
        <setting propertyKey="@Properties.proxyUrl" title="@Strings.SettingProxyTitle">
            <settingConfig type="alphaNumeric" />
        </setting>
    </settings>
</resources>
`;
mkdirSync(dirname(settingsFile), { recursive: true });
writeFileSync(settingsFile, settingsXml, 'utf8');
console.log(`wrote ${settingsFile}`);
